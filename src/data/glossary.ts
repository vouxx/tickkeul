/** 핵심 용어 + 생성 용어. 같은 용어 이름은 먼저 나온 것(핵심 용어)을 남긴다 */
export const glossary: Term[] = (() => {
  const seen = new Set<string>();
  const norm = (s: string) => s.replace(/\s|\(.*?\)/g, "").toLowerCase();
  return [...coreTerms, ...generatedTerms].filter((t) => {
    const k = norm(t.term);
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
})();

export const getTerm = (id: string) => glossary.find((g) => g.id === id);

export const termsByLevel = (level: Level) => glossary.filter((g) => g.level === level);

/** 날짜로 고르는 오늘의 용어 */
export function termOfDay(day: string) {
  let h = 0;
  for (const c of day) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return glossary[h % glossary.length];
}
